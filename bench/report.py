"""
Turn results/ into tables (CSV + Markdown) and figures (PNG) for Section IV.

  python bench/report.py            -> results/tables/*.csv, results/tables.md, results/figures/*.png
"""
from __future__ import annotations

import csv
import json
import statistics as st
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from bench.evaluate import LABELS, SOURCES, ground_truth, subsets  # noqa: E402

RES = ROOT / "results"
TABLES, FIGS = RES / "tables", RES / "figures"
TB_NAMES = {"shoplite": "ShopLite", "trainticket": "Train Ticket", "crapi": "crAPI"}
TB_ORDER = ["shoplite", "trainticket", "crapi"]
MAIN = ["O", "T", "K", "C", "OTKC"]


def name(combo: str) -> str:
    return "All four" if combo == "OTKC" else " + ".join(LABELS[k] for k in combo)


def ms(xs, digits=3):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "n/a"
    m = st.fmean(xs)
    if len(xs) == 1 or digits == 0:
        return f"{m:.{digits}f}"
    return f"{m:.{digits}f} ± {st.stdev(xs):.{digits}f}"


def load_grid():
    runs = defaultdict(list)
    for f in sorted((RES / "grid").glob("*/run.json")):
        r = json.loads(f.read_text())
        runs[(r["testbed"], r["condition"])].append(r)
    return runs


class Out:
    def __init__(self):
        self.md = ["# Section IV result tables", "", "# Phase 1: extraction", "",
                   "Generated by `python bench/report.py` from `results/`. Values are mean ± standard deviation over seeds.", ""]

    def table(self, slug, title, header, rows, note=None):
        TABLES.mkdir(parents=True, exist_ok=True)
        with (TABLES / f"{slug}.csv").open("w", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(header)
            w.writerows(rows)
        self.md += [f"## {title}", ""]
        if note:
            self.md += [note, ""]
        self.md.append("| " + " | ".join(header) + " |")
        self.md.append("|" + "|".join("---" for _ in header) + "|")
        self.md += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
        self.md.append("")


def g(r, combo, metric, key, which="subsets"):
    return r["metrics"][which][combo][metric][key]


def main():
    runs = load_grid()
    out = Out()
    FIGS.mkdir(parents=True, exist_ok=True)

    # ---------------------------------------------------------------- T1 testbeds
    rows = []
    for tb in TB_ORDER:
        gt = ground_truth(tb)
        topo = gt["topology"]
        rs = runs.get((tb, "C1"), [])
        eps = gt["endpoints"]
        rows.append([TB_NAMES[tb], len(topo["services"]) + (0 if any(s["name"] == gt["gateway"] for s in topo["services"]) else 1),
                     len(eps), sum(e["documented"] for e in eps), sum(not e["documented"] for e in eps),
                     sum(e["public"] for e in eps), len(gt["edges"]),
                     ms([g(r, "OTKC", "M1", "exercised") for r in rs], 0),
                     topo.get("documentation"), (topo.get("source") or {}).get("repo", "this repo (demo_target/)")])
    out.table("t1_testbeds", "Table 1. Testbeds and ground truth",
              ["Testbed", "Services", "GT endpoints", "Documented", "Undocumented", "Public via gateway", "GT edges",
               "Exercised per run", "Spec source", "Origin"], rows)

    # ---------------------------------------------------------------- T2 coverage (M1)
    rows = []
    for tb in TB_ORDER:
        for cond in ("C1", "C2"):
            rs = runs.get((tb, cond), [])
            if not rs:
                continue
            for combo in MAIN:
                rows.append([TB_NAMES[tb], cond, name(combo),
                             ms([g(r, combo, "M1", "recall_all") for r in rs]),
                             ms([g(r, combo, "M1", "recall_observable") for r in rs]),
                             ms([g(r, combo, "M1", "precision") for r in rs]),
                             ms([g(r, combo, "M1", "f1") for r in rs]),
                             ms([g(r, combo, "M1", "entries") for r in rs], 1)])
    out.table("t2_coverage", "Table 2. Discovery coverage (M1): single sources vs all four",
              ["Testbed", "Cond.", "Sources", "Recall (all)", "Recall (observable)", "Precision", "F1", "Inventory size"], rows,
              "Recall (all) is over every endpoint in the source code. Recall (observable) is over endpoints that are "
              "documented or received traffic in that run; nothing passive can find the rest. Precision is strict: a second "
              "inventory entry for the same endpoint counts as a false positive.")

    # ---------------------------------------------------------------- T3 ablation (C2, all 15)
    rows = []
    for combo in subsets():
        row = [name(combo)]
        for tb in TB_ORDER:
            rs = runs.get((tb, "C2"), [])
            row += [ms([g(r, combo, "M1", "recall_observable") for r in rs], 2),
                    ms([g(r, combo, "M1", "precision") for r in rs], 2)]
        rows.append(row)
    hdr = ["Sources"] + [f"{TB_NAMES[t]} {m}" for t in TB_ORDER for m in ("R_obs", "P")]
    out.table("t3_ablation_c2", "Table 3. Source ablation under the realistic condition (C2)", hdr, rows)

    # ---------------------------------------------------------------- T4 duplicates & normalization (M2)
    rows = []
    for tb in TB_ORDER:
        for cond in ("C1", "C2"):
            rs = runs.get((tb, cond), [])
            if not rs:
                continue
            raw = lambda k: [r["metrics"]["raw"][k] for r in rs]  # noqa: E731
            rows.append([TB_NAMES[tb], cond, ms(raw("flows"), 0), ms(raw("distinct_concrete_paths"), 0),
                         ms(raw("entries_single_sources_total"), 0), ms(raw("entries_merged"), 0),
                         ms(raw("duplicates_collapsed"), 0),
                         ms([g(r, "T", "M2", "fragments") for r in rs], 1),
                         ms([g(r, "OTKC", "M2", "fragments", "reconcile_off") for r in rs], 1),
                         ms([g(r, "OTKC", "M2", "fragments") for r in rs], 1),
                         ms([g(r, "OTKC", "M2", "reconciled") for r in rs], 1),
                         ms([g(r, "OTKC", "M1", "precision", "reconcile_off") for r in rs]),
                         ms([g(r, "OTKC", "M1", "precision") for r in rs])])
    out.table("t4_normalization", "Table 4. Duplicate identification and path normalization (M2)",
              ["Testbed", "Cond.", "Captured flows", "Distinct concrete paths", "Entries, sum of single-source inventories",
               "Entries, merged", "Duplicates collapsed", "Fragments, traffic only", "Fragments, all four, no reconciliation",
               "Fragments, all four", "Paths reconciled", "Precision, no reconciliation", "Precision, with reconciliation"], rows,
              "A fragment is an inventory entry whose path still holds a concrete value (a station name, a train number, "
              "a non-numeric ID) so it splits one endpoint into many.")

    # ---------------------------------------------------------------- T5 observation accuracy (M3)
    rows = []
    for tb in TB_ORDER:
        for cond in ("C1", "C2"):
            rs = runs.get((tb, cond), [])
            if not rs:
                continue
            for combo in ("T", "OT", "OTKC"):
                rows.append([TB_NAMES[tb], cond, name(combo),
                             ms([g(r, combo, "M3", "service_attribution") for r in rs]),
                             ms([g(r, combo, "M3", "auth_decided") for r in rs]),
                             ms([g(r, combo, "M3", "auth_accuracy") for r in rs]),
                             ms([g(r, combo, "M3", "label_accuracy") for r in rs]),
                             ms([g(r, combo, "M3", "shadow_precision") for r in rs]),
                             ms([g(r, combo, "M3", "shadow_recall") for r in rs]),
                             ms([g(r, combo, "M3", "true_shadow") for r in rs], 0)])
    out.table("t5_observation", "Table 5. Runtime observation accuracy (M3)",
              ["Testbed", "Cond.", "Sources", "Service attribution", "Auth decided", "Auth accuracy", "Inventory label accuracy",
               "Shadow precision", "Shadow recall", "True shadow endpoints"], rows,
              "Auth decided is the share of found endpoints for which traffic held enough anonymous requests to call "
              "authentication enforced or not enforced. Auth accuracy is measured on those. Labels: documented, shadow "
              "(served but not in any spec), zombie (deprecated but still served), dormant (documented, never seen).")

    # label confusion, all four, pooled over seeds and conditions
    conf = defaultdict(Counter)
    for (tb, cond), rs in runs.items():
        for r in rs:
            conf[tb].update(g(r, "OTKC", "M3", "label_confusion"))
    rows = [[TB_NAMES[tb], k.replace("->", " → "), v] for tb in TB_ORDER for k, v in sorted(conf[tb].items())]
    out.table("t5b_label_confusion", "Table 5b. Inventory label confusion, all four sources (true → predicted, pooled)",
              ["Testbed", "True → predicted", "Count"], rows)

    # ---------------------------------------------------------------- T6 dependencies (M4)
    rows = []
    for tb in TB_ORDER:
        for cond in ("C1", "C2"):
            rs = runs.get((tb, cond), [])
            if not rs:
                continue
            for combo in ("K", "C", "KC", "OTKC"):
                rows.append([TB_NAMES[tb], cond, name(combo),
                             ms([g(r, combo, "M4", "found_edges") for r in rs], 1),
                             ms([g(r, combo, "M4", "precision") for r in rs]),
                             ms([g(r, combo, "M4", "recall_all") for r in rs]),
                             ms([g(r, combo, "M4", "recall_exercised") for r in rs]),
                             ms([g(r, combo, "M4", "gt_edges") for r in rs], 0),
                             ms([g(r, combo, "M4", "exercised_edges") for r in rs], 1)])
    out.table("t6_dependencies", "Table 6. Service dependency identification (M4)",
              ["Testbed", "Cond.", "Sources", "Edges found", "Precision", "Recall (all)", "Recall (exercised)",
               "GT edges", "Exercised edges"], rows,
              "Runtime traffic and OpenAPI contribute no edges: on a single host every caller has the same address, "
              "so caller identity comes only from traces, workload environment variables and gateway routes.")

    # ---------------------------------------------------------------- T7 processing performance (M5)
    rows = []
    for tb in TB_ORDER:
        for cond in ("C1", "C2"):
            rs = runs.get((tb, cond), [])
            if not rs:
                continue
            pe = [r["perf"]["extract"] for r in rs]
            pn = [r["perf"]["normalize"] for r in rs]
            rows.append([TB_NAMES[tb], cond, ms([p["detail"]["runtime_traffic"] for p in pe], 0),
                         ms([p["detail"]["openapi"] for p in pe], 0), ms([p["detail"]["infrastructure"] for p in pe], 0),
                         ms([p["detail"]["callchain"] for p in pe], 0), ms([p["wall_ms"] for p in pe], 0),
                         ms([p["peak_rss_mb"] for p in pe], 1), ms([p["wall_ms"] for p in pn], 0),
                         ms([p["peak_rss_mb"] for p in pn], 1)])
    out.table("t7_performance", "Table 7. Processing time and memory per run (M5)",
              ["Testbed", "Cond.", "Traffic (ms)", "OpenAPI (ms)", "K8s/gateway (ms)", "Traces (ms)", "Phase 1 total (ms)",
               "Phase 1 peak RSS (MB)", "Phase 2 normalize (ms)", "Phase 2 peak RSS (MB)"], rows,
              "Phase 1 total includes Python start-up and imports. OpenAPI time is dominated by live probing over HTTP.")

    # ---------------------------------------------------------------- overhead
    for idx, f in enumerate(sorted((RES / "overhead").glob("*-overhead.json"),
                                   key=lambda f: TB_ORDER.index(f.name.split("-")[0]))):
        data = json.loads(f.read_text())
        by = defaultdict(list)
        for d in data:
            by[d["capture"]].append(d)
        base = st.fmean(d["p50"] for d in by["none"])
        base95 = st.fmean(d["p95"] for d in by["none"])
        lbl = {"none": "Direct to gateway", "ns": "mitmproxy north-south", "ns+ew": "mitmproxy north-south + east-west"}
        rows = []
        for cap in ("none", "ns", "ns+ew"):
            ds = by[cap]
            p50, p95 = st.fmean(d["p50"] for d in ds), st.fmean(d["p95"] for d in ds)
            thr = [d["requests"] / d["wall_s"] for d in ds]
            rows.append([lbl[cap], len(ds), ms([d["p50"] for d in ds], 1), ms([d["p95"] for d in ds], 1),
                         f"{p50 - base:+.1f}", f"{p95 - base95:+.1f}", ms(thr, 0)])
        tb = data[0]["testbed"]
        out.table(f"t8_overhead_{tb}", f"Table 8{'abc'[idx]}. Capture overhead on request latency ({TB_NAMES[tb]})",
                  ["Capture", "Reps", "p50 (ms)", "p95 (ms)", "Δp50 vs direct", "Δp95 vs direct", "Throughput (req/s)"], rows,
                  "Same workload, concurrency 8. All processes share one host, so absolute numbers include CPU contention.")
        _fig_overhead(by, lbl, tb)

    # ---------------------------------------------------------------- scale
    for f in sorted((RES / "scale").glob("*-scale.json")):
        data = json.loads(f.read_text())
        tb = f.name.split("-")[0]
        rows = [[f"×{d['factor']}", d["flows"], d["span_lines"], d["traffic_ms"], d["traces_ms"], d["extract_ms"],
                 d["extract_rss_mb"], d["normalize_ms"], d["normalize_rss_mb"], d["inventory"]] for d in data]
        out.table(f"t9_scale_{tb}", f"Table 9. Scalability with capture volume ({TB_NAMES[tb]})",
                  ["Volume", "Flows", "Span records", "Traffic extractor (ms)", "Trace extractor (ms)", "Phase 1 total (ms)",
                   "Phase 1 peak RSS (MB)", "Normalize (ms)", "Normalize peak RSS (MB)", "Inventory entries"], rows,
                  "One C1 capture copied k times with fresh IDs in every copy. OpenAPI probing is off (nothing is running). "
                  "A stable inventory size means the extra volume added no spurious entries.")
        _fig_scale(data, tb)

    # ---------------------------------------------------------------- curve
    for f in sorted((RES / "curve").glob("*-curve.json")):
        data = json.loads(f.read_text())
        tb = f.name.split("-")[0]
        by = defaultdict(list)
        for d in data:
            by[d["requests"]].append(d)
        rows = [[n, len(ds), ms([d["T"] for d in ds]), ms([d["C"] for d in ds]), ms([d["TC"] for d in ds]),
                 ms([d["OTKC"] for d in ds]), ms([d["edges_all"] for d in ds])] for n, ds in sorted(by.items())]
        out.table(f"t10_curve_{tb}", f"Table 10. Recall vs workload size ({TB_NAMES[tb]}, C1, recall over all endpoints)",
                  ["Requests", "Seeds", "Traffic", "Traces", "Traffic + Traces", "All four", "Edge recall, all four"], rows,
                  "Pure Zipf sampling over every public endpoint, no per-endpoint minimum.")
        _fig_curve(by, tb)

    _fig_ablation(runs)
    _fig_main(runs)
    from bench.report_threat import threat_tables
    threat_tables(out)
    (RES / "tables.md").write_text("\n".join(out.md))
    print(f"wrote {RES / 'tables.md'} and {len(list(FIGS.glob('*.png')))} figures")


# ---------------------------------------------------------------- figures
def _plt():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False, "figure.dpi": 150})
    return plt


def _fig_main(runs):
    plt = _plt()
    fig, axes = plt.subplots(1, 3, figsize=(10, 3.2), sharey=True)
    colors = {"C1": "#4C72B0", "C2": "#DD8452"}
    for ax, tb in zip(axes, TB_ORDER):
        x = range(len(MAIN))
        for i, cond in enumerate(("C1", "C2")):
            rs = runs.get((tb, cond), [])
            if not rs:
                continue
            vals = [st.fmean(g(r, c, "M1", "recall_observable") for r in rs) for c in MAIN]
            ax.bar([j + (i - 0.5) * 0.38 for j in x], vals, 0.38, label=cond, color=colors[cond])
        ax.set_xticks(list(x), ["OpenAPI", "Traffic", "K8s", "Traces", "All"], rotation=0)
        ax.set_title(TB_NAMES[tb])
        ax.set_ylim(0, 1.05)
    axes[0].set_ylabel("Recall (observable endpoints)")
    axes[0].legend(frameon=False)
    fig.tight_layout()
    fig.savefig(FIGS / "fig_recall_by_source.png")
    plt.close(fig)


def _fig_ablation(runs):
    plt = _plt()
    combos = list(subsets())
    data = [[st.fmean(g(r, c, "M1", "f1") for r in runs[(tb, "C2")]) if runs.get((tb, "C2")) else 0 for tb in TB_ORDER]
            for c in combos]
    fig, ax = plt.subplots(figsize=(4.6, 5.2))
    im = ax.imshow(data, cmap="viridis", vmin=0, vmax=1, aspect="auto")
    ax.set_xticks(range(len(TB_ORDER)), [TB_NAMES[t] for t in TB_ORDER])
    ax.set_yticks(range(len(combos)), ["+".join(combo) for combo in combos])
    for i, row in enumerate(data):
        for j, v in enumerate(row):
            ax.text(j, i, f"{v:.2f}", ha="center", va="center", color="white" if v < 0.6 else "black", fontsize=7)
    ax.set_title("F1 by source subset (C2)\nO=OpenAPI T=Traffic K=K8s/gateway C=Traces", fontsize=8)
    fig.colorbar(im, ax=ax, fraction=0.04)
    fig.tight_layout()
    fig.savefig(FIGS / "fig_ablation_f1.png")
    plt.close(fig)


def _fig_curve(by, tb):
    plt = _plt()
    fig, ax = plt.subplots(figsize=(4.8, 3.2))
    ns = sorted(by)
    for key, lbl, style in (("T", "Traffic only", "-"), ("TC", "Traffic + Traces", "-"),
                            ("C", "Traces only (same as Traffic + Traces here)", ":"), ("OTKC", "All four", "-")):
        ax.plot(ns, [st.fmean(d[key] for d in by[n]) for n in ns], marker="o", ms=3, label=lbl, linestyle=style,
                lw=2.4 if key == "C" else 1.5)
    ax.set_xscale("log")
    ax.set_xlabel("Requests in workload")
    ax.set_ylabel("Recall (all endpoints)")
    ax.set_ylim(0, 1.02)
    ax.legend(frameon=False, fontsize=7)
    ax.set_title(TB_NAMES[tb])
    fig.tight_layout()
    fig.savefig(FIGS / f"fig_curve_{tb}.png")
    plt.close(fig)


def _fig_scale(data, tb):
    plt = _plt()
    fig, ax = plt.subplots(figsize=(4.8, 3.2))
    x = [d["flows"] for d in data]
    ax.plot(x, [d["traffic_ms"] for d in data], marker="o", ms=3, label="Traffic extractor")
    ax.plot(x, [d["traces_ms"] for d in data], marker="o", ms=3, label="Trace extractor")
    ax.plot(x, [d["normalize_ms"] for d in data], marker="o", ms=3, label="Normalizer")
    ax.xaxis.set_major_formatter(lambda v, _: f"{v / 1000:.0f}k")
    ax.set_xlabel("Captured flows")
    ax.set_ylabel("Time (ms)")
    ax.legend(frameon=False, fontsize=7)
    ax.set_title(f"{TB_NAMES[tb]}: processing time vs volume")
    fig.tight_layout()
    fig.savefig(FIGS / f"fig_scale_{tb}.png")
    plt.close(fig)


def _fig_overhead(by, lbl, tb):
    plt = _plt()
    fig, ax = plt.subplots(figsize=(4.8, 3.0))
    caps = ["none", "ns", "ns+ew"]
    p50 = [st.fmean(d["p50"] for d in by[c]) for c in caps]
    p95 = [st.fmean(d["p95"] for d in by[c]) for c in caps]
    x = range(len(caps))
    ax.bar([i - 0.2 for i in x], p50, 0.4, label="p50")
    ax.bar([i + 0.2 for i in x], p95, 0.4, label="p95")
    ax.set_xticks(list(x), ["Direct", "N-S", "N-S + E-W"])
    ax.set_ylabel("Latency (ms)")
    ax.legend(frameon=False)
    ax.set_title(f"{TB_NAMES[tb]}: capture overhead")
    fig.tight_layout()
    fig.savefig(FIGS / f"fig_overhead_{tb}.png")
    plt.close(fig)


if __name__ == "__main__":
    main()
