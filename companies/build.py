"""
Builds the ten test companies from their definitions.

    python companies/build.py            write every company's files
    python companies/build.py --check    exit 1 if a generated file is out of date

Each companies/<id>/company.yaml describes one company: its services and routes, its
gateway, how it deploys, and the weaknesses planted in it on purpose. From that file
this script writes, in the same folder:

  company.json          what the services and the traffic generator read at run time
  docker-compose.yml    the company's Docker (its own network, <id>-net)
  k8s/                  the company's deployment manifests (what ATG reads; never applied)
  gateway/              gateway configuration that is not a Kubernetes object (nginx, Spring Cloud Gateway)
  live-specs/           the OpenAPI documents the services publish at run time
  specs/                OpenAPI documents kept as files in the company's repository
  atg-target.yaml       ATG's Phase 1 configuration for this company
  atg.env               the three settings START and the experiment use (network, gateway, folder)
  ground-truth.json     every endpoint, the planted weaknesses and the negative controls, for scoring
  README.md             one page about the company

The secure baseline every company starts from: pinned image tags, non-root containers,
resource limits, ClusterIP services, a NetworkPolicy for every workload, TLS on the
Ingress, secrets referenced from a secret store (no values in the repository), a live
OpenAPI document for every service, tracing everywhere, authentication and owner checks
on every route, and rate limiting on the login. Each planted weakness is a declared
deviation from that baseline, listed under `planted:` with the ATG rule expected to
report it. `not_flaws:` lists things that look like a weakness but are not, so a finding
there is a false positive.
"""
