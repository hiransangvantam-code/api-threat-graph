class Dumper(yaml.SafeDumper):
    pass


def _str(dumper, s):
    if "\n" in s:
        return dumper.represent_scalar("tag:yaml.org,2002:str", s, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", s)


Dumper.add_representer(str, _str)


def ydump(obj) -> str:
    return yaml.dump(obj, Dumper=Dumper, sort_keys=False, width=120, allow_unicode=True)


def ydump_all(docs) -> str:
    return yaml.dump_all(docs, Dumper=Dumper, sort_keys=False, width=120, allow_unicode=True)


def ep_id(service: str, method: str, path: str) -> str:
    return f"ep:{service}:{method.upper()}:{re.sub(r'{[^}]*}', '{}', path)}"


def parse_call(spec, default_forward=True) -> dict:
    """'POST ledger-service /ledger/entries' or {to: ..., forward_auth: false, body: {...}}"""
    d = spec if isinstance(spec, dict) else {"to": spec}
    method, svc, path = d["to"].split()
    return {"method": method, "service": svc, "path": path,
            "forward_auth": d.get("forward_auth", default_forward), "body": d.get("body")}


# ============================================================ loading
def load(cid: str) -> dict:
    c = yaml.safe_load((HERE / cid / "company.yaml").read_text(encoding="utf-8"))
    assert c["id"] == cid, cid
    lang = c["language"]
    c.setdefault("credential", "bearer")
    c.setdefault("mtls", False)
    c.setdefault("namespace", cid)
    c.setdefault("external", {})
    c.setdefault("cron", [])
    c.setdefault("planted", [])
    c.setdefault("not_flaws", [])
    gw = c["gateway"]
    gw.setdefault("tls", True)
    gw.setdefault("traced", True)
    gw.setdefault("flaws", [])
    gw["port"] = GW_PORT[gw["type"]]
    for r in gw["routes"]:
        r.setdefault("auth", True)
        r.setdefault("rate_limit", 0)
        r.setdefault("to", r["prefix"])
    auth_name = c.get("auth_service", "auth-service")
    c["auth_service"] = auth_name
    services = {}
    for name, s in (c.get("services") or {}).items():
        s = s or {}
        s.setdefault("version", "1.0.0")
        s.setdefault("flaws", [])
        s.setdefault("spec", "live")
        s["port"] = LANG_PORT[lang]
        routes = []
        for key, r in (s.get("routes") or {}).items():
            method, path = key.split(" ", 1)
            r = dict(r or {})
            r.update(method=method, path=path)
            r.setdefault("auth", "user")
            r.setdefault("in_spec", True)
            r.setdefault("deprecated", False)
            r["calls"] = [parse_call(x) for x in r.get("calls", [])]
            r["external"] = [dict(zip(("method", "host", "path"), x.split())) for x in r.get("external", [])]
            routes.append(r)
        if name == auth_name:  # the login and token check every company has
            routes = [{"method": "POST", "path": "/auth/session", "auth": "none", "builtin": True, "in_spec": True,
                       "deprecated": False, "calls": [], "external": [],
                       "body": {"user": "$user"},
                       "returns": ({"user": "c1", "role": "customer"} if c["credential"] == "cookie" else
                                   {"user": "c1", "role": "customer", "access_token": "x", "token_type": "Bearer"})},
                      {"method": "GET", "path": "/auth/introspect", "auth": "bearer", "builtin": True, "in_spec": True,
                       "deprecated": False, "calls": [], "external": [],
                       "returns": {"user": "c1", "role": "customer", "active": True}}] + routes
        s["routes"] = routes
        services[name] = s
    c["services"] = services
    ext = {}
    for name, x in c["external"].items():
        x = x or {}
        ext[name] = {"port": x.get("port", 9000), "routes": [
            {"method": k.split()[0], "path": k.split()[1], "auth": "none", "returns": (v or {}).get("returns", {"status": "ok"}),
             "calls": [], "external": []} for k, v in (x.get("routes") or {}).items()]}
    c["external"] = ext
    for s in services.values():
        for r in s["routes"]:
            for x in r["external"]:
                x["port"] = ext[x["host"]]["port"]
            for cl in r["calls"]:
                cl["port"] = services[cl["service"]]["port"]
    for r in gw["routes"]:
        r["port"] = services[r["service"]]["port"]
    for job in c["cron"]:
        job.setdefault("every", 1)
        job["calls"] = [parse_call(x, default_forward=False) for x in job["calls"]]
        for cl in job["calls"]:
            cl["port"] = services[cl["service"]]["port"]
    return c


def callers_of(c: dict) -> dict:
    """service -> set of workloads that call it (gateway, other services, cron jobs)."""
    out: dict[str, set] = {n: set() for n in c["services"]}
    for r in c["gateway"]["routes"]:
        out[r["service"]].add(c["gateway"]["name"])
    out[c["auth_service"]].add(c["gateway"]["name"])
    for name, s in c["services"].items():
        for r in s["routes"]:
            for cl in r["calls"]:
                out[cl["service"]].add(name)
    for job in c["cron"]:
        for cl in job["calls"]:
            out[cl["service"]].add(f"cron:{job['name']}")
    return out


