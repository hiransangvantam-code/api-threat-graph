# ============================================================ write everything
def outputs(cid: str) -> dict[str, str]:
    c = load(cid)
    out: dict[str, str] = {}
    out["company.json"] = json.dumps(runtime_json(c), indent=1) + "\n"
    out["docker-compose.yml"] = compose(c)
    for f, text in manifests(c).items():
        out[f"k8s/{f}"] = text
    if c["gateway"]["type"] == "nginx":
        out["gateway/nginx.conf"] = nginx_conf(c)
    if c["gateway"]["type"] == "spring-cloud-gateway":
        out["gateway/application.yml"] = scg_config(c)
    for name, s in c["services"].items():
        if s["spec"] == "none":
            continue
        documented = [r for r in s["routes"] if r["in_spec"]]
        if s["spec"] == "stale":
            documented = [r for r in documented if not r.get("since")]
            ext, text = spec_text(c, openapi(c, name, documented, c["spec"]["version"], "1.0.0"))
            out[f"specs/{name}.v1.{ext}"] = text
            continue
        ext, text = spec_text(c, openapi(c, name, documented, c["spec"]["version"], s["version"]))
        out[f"{'live-specs' if s['spec'] == 'live' else 'specs'}/{name}.{ext}"] = text
    out["atg-target.yaml"] = atg_target(c)
    gw = c["gateway"]
    out["atg.env"] = (f"# {c['name']}: settings for START and bench/run_companies.py. {GENERATED}\n"
                      f"TARGET_NETWORK={c['id']}-net\nTARGET_GATEWAY=http://{gw['name']}:{gw['port']}\n"
                      f"TARGET_CONFIG=./companies/{c['id']}\nTARGET_NAME=\"{c['name']}\"\n")
    out["ground-truth.json"] = json.dumps(ground_truth(c), indent=1) + "\n"
    out["README.md"] = readme(c)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only check that the generated files are current")
    ap.add_argument("companies", nargs="*", default=COMPANIES)
    a = ap.parse_args()
    stale = []
    for cid in a.companies:
        folder = HERE / cid
        files = outputs(cid)
        keep = {"company.yaml"} | set(files)
        for f, text in files.items():
            p = folder / f
            if a.check:
                if not p.exists() or p.read_text(encoding="utf-8") != text:
                    stale.append(str(p.relative_to(HERE)))
                continue
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8")
        for p in folder.rglob("*"):
            if p.is_file() and str(p.relative_to(folder)).replace("\\", "/") not in keep:
                if a.check:
                    stale.append(f"{p.relative_to(HERE)} (not generated any more)")
                else:
                    p.unlink()
        if not a.check:
            g = json.loads(files["ground-truth.json"])
            print(f"{cid:10s} {len(g['endpoints']):3d} endpoints, {len(g['planted']):2d} planted, "
                  f"{len(g['not_flaws'])} negative controls, {len(files)} files")
    if a.check and stale:
        print("out of date (run python companies/build.py):\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
