GENERATED = "Generated by opensource/build.py from system.yaml. Edit system.yaml, not this file."
INFRA_PATHS = re.compile(r"^/(health|healthz|_healthz|ready|readyz|livez|metrics|version|whereami)$")


def _routes(spec: dict, services: dict) -> list[dict]:
    out = []
    for key, r in (spec or {}).items():
        method, path = key.split(" ", 1)
        r = dict(r or {})
        r.update(method=method, path=path)
        r.setdefault("auth", "none")
        r["calls"] = [parse_call(x) for x in r.get("calls", [])]
        for c in r["calls"]:
            c["port"] = services[c["service"]]["port"]
        out.append(r)
    return out


def load(sid: str) -> dict:
    s = yaml.safe_load((HERE / sid / "system.yaml").read_text(encoding="utf-8"))
    assert s["id"] == sid, sid
    s.setdefault("credential", "bearer")
    s.setdefault("external", {})
    s.setdefault("cron", [])
    s.setdefault("labels", [])
    s.setdefault("artifacts", {})
    services = s["services"]
    for name, sv in services.items():
        sv.setdefault("traced", s.get("traced", True))
    for name, sv in services.items():
        sv["routes"] = _routes(sv.get("routes"), {**services, **{k: {"port": v.get("port", 9000)} for k, v in s["external"].items()}})
        for r in sv["routes"]:
            r["external"] = [dict(zip(("method", "host", "path"), x.split())) for x in r.get("external", [])]
            for x in r["external"]:
                x["port"] = (s["external"][x["host"]] or {}).get("port", 9000)
    gw = s.get("gateway")
    if gw:
        gw.setdefault("traced", s.get("traced", True))
        for r in gw["routes"]:
            r.setdefault("to", r["prefix"])
            r.setdefault("auth", False)
            r["port"] = services[r["service"]]["port"]
        gw["own"] = _routes(gw.get("own_routes"), services)
    for job in s["cron"]:
        job.setdefault("every", 1)
        job["calls"] = [parse_call(x, default_forward=False) for x in job["calls"]]
        for c in job["calls"]:
            c["port"] = services[c["service"]]["port"]
    a = s.get("auth")
    if a:
        m, p = a["login"].split(" ", 1)
        a["login"] = {"method": m, "path": p}
        a["port"] = services[a["service"]]["port"]
        if a.get("entry"):
            em = re.match(r"^(\w+) (\S+) \((\S+)\)$", a["entry"])
            a["entry"] = {"method": em.group(1), "path": em.group(2), "service": em.group(3)}
        # the login (and the token check, when the real system has one) are operations too;
        # the runtime serves them itself
        builtin = [{"method": m, "path": p, "auth": "none", "builtin": True, "calls": [], "external": []}]
        if a.get("introspect"):
            builtin.append({"method": "GET", "path": a["introspect"], "auth": "user", "builtin": True, "calls": [],
                            "external": []})
        services[a["service"]]["routes"] = builtin + services[a["service"]]["routes"]
    return s


def spec_services(s: dict) -> set:
    return set((s.get("spec") or {}).get("services", []))


# ============================================================ runtime configuration
def _rt_route(r: dict) -> dict:
    rr = {k: r[k] for k in ("method", "path", "auth")}
    for k in ("owner", "errors_every", "status", "returns", "login_proxy"):
        if r.get(k) is not None:
            rr[k] = r[k]
    if r.get("owner_check") is False:
        rr["owner_check"] = False
    if r["calls"]:
        rr["calls"] = [{**{k: c[k] for k in ("service", "port", "method", "path", "forward_auth", "body")},
                        **({"service_key": True} if c.get("service_key") else {})} for c in r["calls"]]
    if r.get("external"):
        rr["external"] = r["external"]
    traffic = {k: r[k] for k in ("weight", "ua", "client", "query", "body", "credential_in_query") if k in r}
    if traffic:
        rr["traffic"] = traffic
    return rr


def runtime_json(s: dict) -> dict:
    gw = s.get("gateway")
    a = s.get("auth")
    out = {"_comment": GENERATED, "id": s["id"], "name": s["name"], "credential": s["credential"],
           "auth_service": None, "gateway": None, "edge": s.get("edge"), "services": {}, "cron": []}
    if a:
        out["auth_service"] = {"name": a["service"], "port": a["port"], "login": a["login"],
                               **{k: a[k] for k in ("introspect", "user_field", "login_extra", "cookie", "token",
                                                    "token_in_body", "entry") if a.get(k) is not None}}
    if gw:
        out["gateway"] = {"name": gw["name"], "type": gw["type"], "port": gw["port"], "traced": gw["traced"],
                          "routes": [{"prefix": r["prefix"], "service": r["service"], "port": r["port"], "from": r["prefix"],
                                      "to": r["to"], "auth": bool(r["auth"]), "limit_per_min": 0,
                                      **({"methods": r["methods"]} if r.get("methods") else {})}
                                     for r in sorted(gw["routes"], key=lambda r: -len(r["prefix"]))],
                          "own_routes": [_rt_route(r) for r in gw["own"]]}
    sp = spec_services(s)
    for name, sv in s["services"].items():
        spec = {"path": s["spec"]["path"], "file": f"live-specs/{name}.json", "type": "application/json"} if name in sp else None
        out["services"][name] = {"port": sv["port"], "traced": sv["traced"], "verify": sv.get("verify"), "spec": spec,
                                 "routes": [_rt_route(r) for r in sv["routes"] if not r.get("builtin")]}
    for name, x in s["external"].items():
        x = x or {}
        out["services"][name] = {"port": x.get("port", 9000), "traced": False, "external": True, "spec": None,
                                 "routes": [{"method": k.split()[0], "path": k.split()[1], "auth": "none",
                                             "returns": (v or {}).get("returns", {"status": "ok"})}
                                            for k, v in (x.get("routes") or {}).items()]}
    out["cron"] = [{"name": j["name"], "every": j["every"],
                    "calls": [{k: c[k] for k in ("service", "port", "method", "path", "body")} for c in j["calls"]]}
                   for j in s["cron"]]
    return out


def live_spec(s: dict, name: str) -> dict:
    """What springdoc publishes for a Spring service: every controller operation."""
    sv = s["services"][name]
    paths: dict = {}
    for r in sv["routes"]:
        op = {"operationId": re.sub(r"[^a-zA-Z0-9]+", "_", f"{r['method'].lower()}{r['path']}").strip("_"),
              "parameters": [{"name": p, "in": "path", "required": True, "schema": {"type": "string"}}
                             for p in re.findall(r"{([^}]+)}", r["path"])]
              + [{"name": q, "in": "query", "schema": {"type": "string"}} for q in (r.get("query") or {})],
              "responses": {str(r.get("status", 200)): {"description": "OK", "content": {"application/json": {
                  "schema": schema_of(r.get("returns") or {})}}}}}
        if r.get("body") is not None:
            op["requestBody"] = {"content": {"application/json": {"schema": schema_of(r["body"])}}}
        if r["auth"] == "user":
            op["security"] = [{"bearerAuth": []}]
        elif r["auth"] == "key":
            op["security"] = [{"apiKey": []}]
        if r.get("deprecated"):
            op["deprecated"] = True
        paths.setdefault(r["path"], {})[r["method"].lower()] = op
    return {"openapi": "3.0.1", "info": {"title": f"{name} API", "version": "v1"},
            "servers": [{"url": f"http://{name}:{sv['port']}"}], "paths": paths,
            "components": {"securitySchemes": {"bearerAuth": {"type": "http", "scheme": "bearer", "bearerFormat": "JWT"},
                                               "apiKey": {"type": "apiKey", "in": "header", "name": "Authorization"}}}}


