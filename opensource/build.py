"""
Builds the stand-in runs of the ten open-source systems from their definitions.

    python opensource/fetch.py                download the systems' code (once)
    python opensource/build.py                write every system's files
    python opensource/build.py --check        exit 1 if a generated file is out of date

opensource/<id>/system.yaml records, from each system's own source code, its services, ports,
HTTP (and gRPC) operations, who calls whom, and where it checks a login. It also records the
weaknesses we found by reading the code, with the file they are in. From it this script writes:

  company.json        what the stand-in services and the traffic generator read (Python runtime)
  docker-compose.yml  the stand-in system: one container per real service, with the real
                      service name and port, on its own network <id>-net
  atg-target.yaml     ATG's Phase 1 configuration: the REAL manifests, gateway configuration and
                      API documents from upstream/, plus the stand-ins' traffic and traces
  atg.env             network, gateway address and folder, for START and the benchmark
  ground-truth.json   every operation in the code, and every weakness label: the ones written
                      by hand in system.yaml and the configuration ones computed by
                      config_labels.py from the real manifests or compose file
  live-specs/         API documents for the services that publish one while running (springdoc)

What is real and what is a stand-in: ATG and the other tools read the systems' real
deployment files and API documents. The running services are stand-ins (companies/runtime/
python) that answer the same operations, call the same services and check logins where the
real code does; they do not run the real business logic.
"""
