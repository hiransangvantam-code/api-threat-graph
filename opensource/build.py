def compose(s: dict) -> str:
    net = f"{s['id']}-net"
    signed = (s.get("auth") or {}).get("token") == "signed"

    def svc(name: str, port: int, traced: bool, external=False) -> dict:
        env = {"COMPANY": "/company/company.json", "SERVICE": name}
        if not external:
            env["MESH_PROXY"] = "http://atg-proxy:8081"
            if traced:
                env["OTEL_EXPORTER_OTLP_ENDPOINT"] = "http://atg-collector:4318"
        vols = ["./company.json:/company/company.json:ro"]
        if name in spec_services(s):
            vols.append("./live-specs:/company/live-specs:ro")
        d = {"build": "../../companies/runtime/python", "image": "atg-company-python:1.0", "environment": env,
             "volumes": vols, "networks": [net], "restart": "unless-stopped",
             "healthcheck": {"test": ["CMD", "python", "-c",
                                      f"import urllib.request; urllib.request.urlopen('http://localhost:{port}/health', timeout=2)"],
                             "interval": "2s", "timeout": "3s", "retries": 40}}
        if signed and not external:
            env["TOKEN_KEY_FILE"] = "/keys/token-key"
            d["volumes"].append("keys:/keys:ro")
            d["depends_on"] = {"keygen": {"condition": "service_completed_successfully"}}
        return d

    out: dict = {"name": f"oss-{s['id']}", "services": {}}
    if signed:
        out["services"]["keygen"] = {
            "image": "atg-company-python:1.0", "build": "../../companies/runtime/python", "user": "0", "networks": [net],
            "command": ["python", "-c", "import secrets,os; p='/keys/token-key'; os.path.exists(p) or "
                                        "open(p,'w').write(secrets.token_hex(32))"],
            "volumes": ["keys:/keys"], "restart": "no"}
    if s.get("gateway"):
        g = s["gateway"]
        out["services"][g["name"]] = svc(g["name"], g["port"], g["traced"])
    for name, sv in s["services"].items():
        out["services"][name] = svc(name, sv["port"], sv["traced"])
    for name, x in s["external"].items():
        out["services"][name] = svc(name, (x or {}).get("port", 9000), False, external=True)
    out["services"]["users"] = {"build": "../../companies/runtime/python", "image": "atg-company-python:1.0",
                                "profiles": ["users"], "restart": "no", "networks": [net],
                                "volumes": ["./company.json:/company/company.json:ro"],
                                "command": "python traffic.py --gateway http://atg-proxy:8080 --mesh-proxy http://atg-proxy:8081 "
                                           f"--wait 120 --rounds {s.get('traffic_rounds', 15)}"}
    out["networks"] = {net: {"name": net}}
    if signed:
        out["volumes"] = {"keys": {}}
    head = (f"# {s['name']} ({s['field']}): stand-in services for the open-source benchmark.\n# {GENERATED}\n"
            f"# Real code: {(s['upstream'].get('repo') or s['upstream']['repos'][0]['repo'])}. Same service names and ports;\n"
            f"# the containers run companies/runtime/python, not the system's own code.\n")
    return head + ydump(out)


def edge_url(s: dict) -> str:
    if s.get("gateway"):
        return f"http://{s['gateway']['name']}:{s['gateway']['port']}"
    e = s["edge"] if isinstance(s["edge"], str) else s["edge"][0]
    return f"http://{e}:{s['services'][e]['port']}"


def atg_target(s: dict) -> str:
    smap = {}
    if s.get("gateway"):
        smap[f"{s['gateway']['name']}:{s['gateway']['port']}"] = s["gateway"]["name"]
    smap.update({f"{n}:{sv['port']}": n for n, sv in s["services"].items()})
    live = [{"service": v, "base_url": f"http://{k}"} for k, v in smap.items()]
    art = s["artifacts"]
    infra = {"enabled": True, "manifest_paths": [f"upstream/{p}" for p in art.get("manifests", [])]}
    if art.get("compose"):
        infra["compose_files"] = [f"upstream/{art['compose']}"]
    if art.get("gateway_configs"):
        infra["gateway_configs"] = [{**g, "path": f"upstream/{g['path']}"} for g in art["gateway_configs"]]
    doc = {"target": {"name": s["name"], "service_map": smap},
           "sources": {"runtime_traffic": {"enabled": True, "capture_files": []},
                       "openapi": {"enabled": True, "live_targets": live,
                                   "spec_files": [{**f, "path": f"upstream/{f['path']}"} for f in art.get("spec_files", [])]},
                       "infrastructure": infra,
                       "callchain": {"enabled": True, "trace_paths": []}},
           "output_dir": "output/raw", "report_path": "output/report.html"}
    return (f"# ATG Phase 1 configuration for {s['name']}: the real deployment files under upstream/ (from\n"
            f"# opensource/fetch.py) and the stand-ins' traffic and traces. {GENERATED}\n" + ydump(doc))


def resolve(s: dict, at: str) -> str:
    names = set(s["services"]) | ({s["gateway"]["name"]} if s.get("gateway") else set())
    if at in names or ":" in at:
        return at if ":" in at else f"svc:{at}"
    m = re.match(r"^(GET|POST|PUT|PATCH|DELETE) (\S+)(?: \((\S+)\))?$", at)
    if not m:
        raise SystemExit(f"{s['id']}: cannot read '{at}'")
    method, path, svc = m.groups()
    owners = [n for n, sv in s["services"].items() if any(r["method"] == method and r["path"] == path for r in sv["routes"])]
    if s.get("gateway") and any(r["method"] == method and r["path"] == path for r in s["gateway"]["own"]):
        owners.append(s["gateway"]["name"])
    if svc:
        owners = [o for o in owners if o == svc]
    if len(owners) != 1:
        raise SystemExit(f"{s['id']}: '{at}' matches {owners or 'nothing'}")
    return ep_id(owners[0], method, path)


def _match(route_path: str, call_path: str) -> bool:
    a, b = route_path.strip("/").split("/"), call_path.strip("/").split("/")
    return len(a) == len(b) and all(x == y or x.startswith("{") or y.startswith("{") for x, y in zip(a, b))


def call_graph_labels(s: dict) -> list[dict]:
    """A5 from the call graph in system.yaml: a backend service that another backend service
    calls without a credential, and that answers it (none of the ten turns mTLS on by default)."""
    out, seen = [], set()
    for caller, sv in s["services"].items():
        for r in sv["routes"]:
            for c in r["calls"]:
                callee = s["services"].get(c["service"])
                target = next((x for x in (callee or {}).get("routes", [])
                               if x["method"] == c["method"] and _match(x["path"], c["path"])), None)
                if not target:
                    continue
                anonymous = target["auth"] == "none" or (not c["forward_auth"] and target["auth"] not in ("key",))
                if anonymous and target["auth"] in ("none",) and c["service"] not in seen:
                    seen.add(c["service"])
                    out.append({"cat": "A5", "target": f"svc:{c['service']}", "at": c["service"],
                                "why": f"{caller} calls {c['method']} {c['path']} without a credential, and nothing (mTLS, token) "
                                       "stops any other pod from doing the same.",
                                "evidence": "call graph in system.yaml", "source": "code review"})
    return out


def undocumented_labels(s: dict) -> list[dict]:
    """O1 for operations missing from a service's API document (a document that covers only part
    of the service), from the real spec files in upstream/."""
    out = []
    for f in s["artifacts"].get("spec_files", []):
        p = HERE / s["id"] / "upstream" / f["path"]
        doc = yaml.safe_load(p.read_text(encoding="utf-8"))
        base = (doc.get("basePath") or "").rstrip("/") if "swagger" in doc else ""   # Swagger 2.0: paths sit under basePath
        documented = {(m.upper(), re.sub(r"{[^}]*}", "{}", base + path)) for path, item in (doc.get("paths") or {}).items()
                      for m in item if m in ("get", "post", "put", "patch", "delete")}
        for r in s["services"][f["service"]]["routes"]:
            if INFRA_PATHS.match(r["path"]):
                continue
            if (r["method"], re.sub(r"{[^}]*}", "{}", r["path"])) not in documented:
                out.append({"cat": "O1", "target": ep_id(f["service"], r["method"], r["path"]), "at": f"{r['method']} {r['path']}",
                            "why": f"Not in {f['path']}.", "evidence": f["path"], "source": "deployment files"})
    return out


def ground_truth(s: dict) -> dict:
    eps = []
    pools = [(n, sv["routes"]) for n, sv in s["services"].items()]
    if s.get("gateway"):
        pools.append((s["gateway"]["name"], s["gateway"]["own"]))
    for n, routes in pools:
        for r in routes:
            if INFRA_PATHS.match(r["path"]):
                continue
            eps.append({"service": n, "method": r["method"], "path": r["path"], "id": ep_id(n, r["method"], r["path"])})
    labels = [{"cat": l["cat"], "target": resolve(s, l["at"]), "at": l["at"], "why": l["why"],
               "evidence": l.get("evidence", ""), "source": "code review"} for l in s["labels"]]
    labels += call_graph_labels(s) + undocumented_labels(s)
    seen = set()
    labels = [l for l in labels if not ((l["cat"], l["target"]) in seen or seen.add((l["cat"], l["target"])))]
    for l in config_labels(s, HERE / s["id"] / "upstream"):
        if (l["cat"], l["target"]) not in seen:
            labels.append(l)
            seen.add((l["cat"], l["target"]))
    return {"_comment": GENERATED, "system": s["id"], "name": s["name"], "endpoints": eps, "labels": labels}


def outputs(sid: str) -> dict[str, str]:
    s = load(sid)
    out = {"company.json": json.dumps(runtime_json(s), indent=1) + "\n",
           "docker-compose.yml": compose(s),
           "atg-target.yaml": atg_target(s),
           "atg.env": (f"# {s['name']}: settings for START and bench/run_opensource.py. {GENERATED}\n"
                       f"TARGET_NETWORK={s['id']}-net\nTARGET_GATEWAY={edge_url(s)}\n"
                       f"TARGET_CONFIG=./opensource/{s['id']}\nTARGET_NAME=\"{s['name']}\"\n"),
           "ground-truth.json": json.dumps(ground_truth(s), indent=1) + "\n"}
    for name in sorted(spec_services(s)):
        out[f"live-specs/{name}.json"] = json.dumps(live_spec(s, name), indent=1) + "\n"
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("systems", nargs="*", default=SYSTEMS)
    a = ap.parse_args()
    stale = []
    for sid in a.systems:
        files = outputs(sid)
        for f, text in files.items():
            p = HERE / sid / f
            if a.check:
                if not p.exists() or p.read_text(encoding="utf-8") != text:
                    stale.append(str(p.relative_to(HERE)))
                continue
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8")
        if not a.check:
            g = json.loads(files["ground-truth.json"])
            by = {}
            for l in g["labels"]:
                by[l["source"]] = by.get(l["source"], 0) + 1
            print(f"{sid:18s} {len(g['endpoints']):3d} operations, labels: {by}")
    if stale:
        print("out of date:\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
