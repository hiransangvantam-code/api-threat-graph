"""
Write opensource/real/<id>/load.txt: the anonymous requests the laptop kit sends to a system's real
images, taken from the operations in opensource/<id>/system.yaml.

    python opensource/real/make_load.py            every system that has a kit folder

Rules: an operation behind the gateway (or on the edge service) is called through the sidecar's front
door (atg-proxy:8080) on its public path; any other operation is called on the service itself through
the sidecar's forward proxy. Path parameters become 1. Writes send an empty JSON object, so nothing
personal is ever made up; the service's answer (400, 401, 403 or 2xx) is what ATG needs to see.
Logins, registrations, anything with a password field, DELETEs and gRPC methods are left out.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
OSS = HERE.parent


def public_path(s: dict, svc: str, path: str) -> str | None:
    gw = s.get("gateway")
    if gw:
        for r in gw.get("routes", []):
            if r["service"] == svc:
                to = r.get("to", r["prefix"])
                if path.startswith(to.rstrip("/") + "/") or path == to.rstrip("/") or to == "/":
                    rest = path[len(to.rstrip("/")):] if to != "/" else path
                    return r["prefix"].rstrip("/") + rest
        return None
    edges = s.get("edge")
    edges = [edges] if isinstance(edges, str) else (edges or [])
    return path if edges and svc == edges[0] else None


def lines_for(sid: str) -> list[str]:
    s = yaml.safe_load((OSS / sid / "system.yaml").read_text(encoding="utf-8"))
    auth = s.get("auth") or {}
    login = (auth.get("login") or "").split(" ", 1)[-1]
    out = []
    for svc, d in s["services"].items():
        for op, r in (d.get("routes") or {}).items():
            r = r or {}
            method, path = op.split(" ", 1)
            body = r.get("body")
            if (method == "DELETE" or r.get("client") == "none" or path == login
                    or re.fullmatch(r"/\w+(\.\w+)+/\w+", path)   # gRPC: curl over HTTP/1.1 cannot call it; traces show it
                    or re.search(r"login|register|signup|token", path, re.I)
                    or (isinstance(body, dict) and any("pass" in k.lower() for k in body))):
                continue
            url_path = re.sub(r"{[^}]+}", "1", path)
            pub = public_path(s, svc, path)
            url = (f"http://atg-proxy:8080{re.sub(r'{[^}]+}', '1', pub)}" if pub is not None
                   else f"http://{svc}:{d['port']}{url_path}")
            out.append(f"{method} {url}" + (" {}" if method in ("POST", "PUT", "PATCH") else ""))
    return out


def main() -> int:
    for kit in sorted(p for p in HERE.iterdir() if (p / "kit.env").exists()):
        sid = kit.name
        lines = lines_for(sid)
        head = (f"# {sid}: anonymous requests for the laptop kit, generated by opensource/real/make_load.py\n"
                f"# from opensource/{sid}/system.yaml. Format: METHOD URL [JSON body].\nROUNDS 10\n")
        (kit / "load.txt").write_text(head + "\n".join(lines) + "\n", encoding="utf-8")
        print(f"{sid}: {len(lines)} requests per round")
    return 0


if __name__ == "__main__":
    sys.exit(main())
